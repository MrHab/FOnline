# ---------------------------------------------------------------- построение
def get_collection(name):
    col = bpy.data.collections.get(name)
    if col is None:
        col = bpy.data.collections.new(name)
        bpy.context.scene.collection.children.link(col)
    return col


def make_material(name, color, roughness=0.8):
    mat = bpy.data.materials.get(name)
    if mat is None:
        mat = bpy.data.materials.new(name)
        mat.use_nodes = True
        bsdf = mat.node_tree.nodes.get("Principled BSDF")
        if bsdf:
            bsdf.inputs["Base Color"].default_value = (*color, 1.0)
            bsdf.inputs["Roughness"].default_value = roughness
        mat.diffuse_color = (*color, 1.0)
    return mat


def build_floor(col, mat):
    bm = bmesh.new()
    verts = [bm.verts.new((x, y, 0.0)) for x, y in FLOOR_POLY]
    face = bm.faces.new(verts)
    res = bmesh.ops.extrude_face_region(bm, geom=[face])
    moved = [g for g in res["geom"] if isinstance(g, bmesh.types.BMVert)]
    bmesh.ops.translate(bm, verts=moved, vec=(0, 0, -FLOOR_T))
    bmesh.ops.recalc_face_normals(bm, faces=bm.faces)
    mesh = bpy.data.meshes.new("Пол")
    bm.to_mesh(mesh)
    bm.free()
    obj = bpy.data.objects.new("Пол", mesh)
    obj.data.materials.append(mat)
    col.objects.link(obj)
    return obj


def build_walls(col, name, segs, thickness, height, mat):
    bm = bmesh.new()
    for (x1, y1), (x2, y2) in segs:
        dx, dy = x2 - x1, y2 - y1
        length = math.hypot(dx, dy)
        if length < 1e-6:
            continue
        ang = math.atan2(dy, dx)
        mid = Vector(((x1 + x2) / 2, (y1 + y2) / 2, height / 2))
        mtx = (Matrix.Translation(mid)
               @ Matrix.Rotation(ang, 4, 'Z')
               @ Matrix.Diagonal(Vector((length + thickness, thickness,
                                         height))).to_4x4())
        bmesh.ops.create_cube(bm, size=1.0, matrix=mtx)
    mesh = bpy.data.meshes.new(name)
    bm.to_mesh(mesh)
    bm.free()
    obj = bpy.data.objects.new(name, mesh)
    obj.data.materials.append(mat)
    col.objects.link(obj)
    return obj


def build_labels(col, mat):
    for text, (x, y) in ROOM_LABELS.items():
        curve = bpy.data.curves.new(f"Метка_{text}", type='FONT')
        curve.body = text
        curve.size = 0.7
        curve.align_x = 'CENTER'
        curve.align_y = 'CENTER'
        obj = bpy.data.objects.new(f"Метка_{text}", curve)
        obj.location = (x, y, 0.02)
        obj.data.materials.append(mat)
        col.objects.link(obj)


def main():
    col = get_collection("Техплан_Д1")
    mat_floor = make_material("Техплан_пол", (0.55, 0.50, 0.45))
    mat_outer = make_material("Техплан_стены_наружные", (0.85, 0.83, 0.78))
    mat_inner = make_material("Техплан_перегородки", (0.92, 0.90, 0.86))
    mat_text = make_material("Техплан_текст", (0.10, 0.10, 0.12))

    build_floor(col, mat_floor)
    build_walls(col, "Стены_наружные", OUTER_SEGS, T_OUT, WALL_H, mat_outer)
    build_walls(col, "Перегородки", INNER_SEGS, T_IN, WALL_H, mat_inner)
    build_labels(col, mat_text)


main()
