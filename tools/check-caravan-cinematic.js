'use strict';
const assert = require('node:assert/strict');
const { CINEMATIC_ID, HOLD_MS, beginCaravanCinematic, caravanCinematicHeld, finishCaravanCinematic } = require('../src/server/kromka-caravan-cinematic');
const room = { id: 'randomRuinedRoad#intro_hero', encounterId: 'kromka_caravan_twelve_ambush' };
const player = { id: 'socket-a', characterId: 'hero' };
assert.equal(beginCaravanCinematic(room, player, CINEMATIC_ID, 1000), true);
assert.equal(caravanCinematicHeld(room, 1000 + HOLD_MS - 1), true);
assert.equal(caravanCinematicHeld(room, 1000 + HOLD_MS), false, 'disconnect must not freeze a room forever');
assert.equal(finishCaravanCinematic(room, { characterId: 'intruder' }, CINEMATIC_ID), false);
assert.equal(finishCaravanCinematic(room, player, 'another-film'), false);
assert.equal(finishCaravanCinematic(room, { id: 'socket-b', characterId: 'hero' }, CINEMATIC_ID), true);
assert.equal(caravanCinematicHeld(room, 1001), false);
assert.equal(finishCaravanCinematic(room, player, CINEMATIC_ID), true, 'skip/reconnect completion must be idempotent');
const ordinary = { id: 'randomRuinedRoad', encounterId: room.encounterId };
assert.equal(beginCaravanCinematic(ordinary, player, CINEMATIC_ID), false);
assert.equal(beginCaravanCinematic(room, player, undefined), false, 'tutorial skip must not start a movie hold');
assert.equal(caravanCinematicHeld(ordinary), false);
assert.equal(caravanCinematicHeld(null), false);
console.log('caravan cinematic: private-room protection, ownership, skip, reconnect and timeout PASS');
