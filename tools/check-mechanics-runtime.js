'use strict';
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const h = require('./check-combat-runtime');
const accounts = {};

const qty = (self, id) => (self.inventory || []).filter(r => r.id === id).reduce((s,r) => s + r.qty, 0);

(async () => {
  await h.bootstrapCharacters(accounts);
  const users = JSON.parse(fs.readFileSync(path.join(h.DATA_DIR, 'users.json')));
  const savesPath = path.join(h.DATA_DIR, 'saves.json');
  const saves = JSON.parse(fs.readFileSync(savesPath));
  const stateFor = role => saves.characters[users.users[accounts[role].login].id][accounts[role].characterId].state;
  const donor = stateFor('trade');
  donor.inventory.silver = 500;
  donor.inventory.artifactSpring = 1;
  donor.inventory.artifactDrop = 1;
  donor.inventory.artifactContainer = 1;
  donor.inventory.artifactBelt2 = 1;
  donor.equipment.artifactBelt = 'artifactBelt2';
  donor.artifactRecords = [{ id: 'audit_spring', typeId: 'spring', itemId: 'artifactSpring', hot: false, stabilized: true, ownerCharacterId: accounts.trade.characterId }];
  donor.artifactRecords.push({ id: 'audit_hot', typeId: 'drop', itemId: 'artifactDrop', hot: true, stabilized: false, containerId: 'artifactContainer:1', ownerCharacterId: accounts.trade.characterId });
  donor.artifactSlots = ['audit_spring'];
  const recipient = stateFor('target');
  recipient.currentLocationId = donor.currentLocationId;
  recipient.serverLocationContext = { locationId: donor.currentLocationId };
  recipient.player.x = donor.player.x;
  recipient.player.z = donor.player.z;
  recipient.inventory.artifactBelt2 = 1;
  recipient.equipment.artifactBelt = 'artifactBelt2';
  const shooter = stateFor('cadence');
  shooter.inventory.repairKit = 2;
  shooter.inventory.ui_laserPistol_spare_1 = 1;
  shooter.itemRuntime.ui_laserPistol_spare_1 = { baseId: 'laserPistol', condition: 43, loaded: 0, createdAt: Date.now() };
  const baseUserId = users.users[accounts.persistence.login].id;
  const builder = stateFor('persistence');
  builder.currentLocationId = donor.currentLocationId;
  builder.serverLocationContext = { locationId: donor.currentLocationId };
  builder.player.x = donor.player.x;
  builder.player.z = donor.player.z;
  builder.inventory.scrap = 10;
  builder.inventory.chemicals = 10;
  const baseModule = require(path.join(root, 'src/server/personal-bases'));
  saves.personalBases ||= {};
  const base = baseModule.createPersonalBase(baseUserId);
  base.rights = { granted: false, outcomeId: '', questId: 'personal_aktov_air_rights', grantedAt: 0 };
  builder.kromkaQuestState = { completed: { personal_aktov_air_rights: { outcomeId: 'official', completedAt: Date.now() - 100000 } } };
  base.objects = [{ id: 'audit_bench', typeId: 'medical_bench', x: 6, z: 6, rotation: 0, builtAt: Date.now() - 100000 }];
  base.jobs = Array.from({length: 10}, (_, i) => ({ id: 'audit_old_' + i, typeId: 'filters', startedAt: 1000+i, completesAt: 5000+i, claimed: true }));
  saves.personalBases[baseUserId] = base;
  const siegeConfig = require(path.join(root, 'data/kromka/sieges.json'));
  const siegeModule = require(path.join(root, 'src/server/siege-resolution'));
  const siegeHero = accounts.progression.characterId;
  const siegeClanId = 'audit_siege_clan';
  stateFor('progression').socialState = { clan: { id: siegeClanId, name: 'Audit clan', role: 'Основатель' } };
  saves.kromkaClans.clans[siegeClanId] = { id: siegeClanId, name: 'Audit clan', baseId: '', storage: {}, log: [], lastActiveAt: Date.now(), members: { [siegeHero]: { characterId: siegeHero, role: 'Основатель', joinedAt: Date.now() - 4*86400000 } } };
  const siegeEvent = siegeModule.createSiegeEvent({ id: 'audit_eliminated_siege', baseId: 'hydro2', defenderClanId: 'neutral', startAt: Date.now() - 610000, roomId: 'clanSiege#audit_eliminated_siege' }, siegeConfig);
  Object.assign(siegeEvent, { status: 'active', phase: 'breach', phaseEndsAt: Date.now()+1200000, rosterLocked: true, qualifiedAttackerClanId: siegeClanId, challengers: [{ clanId: siegeClanId, declaredAt: Date.now()-86400000 }], rosters: { [siegeClanId]: [siegeHero] }, respawnWaves: { [siegeClanId]: 3 }, eliminated: { [siegeHero]: { clanId: siegeClanId, at: Date.now()-1000 } } });
  saves.kromkaSieges.events[siegeEvent.id] = siegeEvent;
  fs.writeFileSync(savesPath, JSON.stringify(saves, null, 2));
  await h.startServer();

  const request = async (account, event, data) => {
    const response = await h.socketAck(account.socket, event, data);
    assert.equal(response.ok, true, event + ': ' + JSON.stringify(response));
    return response;
  };
  await h.connectAndJoin(accounts.trade);
  await h.connectAndJoin(accounts.target);
  const rights = await request(accounts.trade, 'personalBaseAction', { action: 'resolveRights', outcomeId: 'official' });
  assert(rights.state.rights.granted);
  assert.equal(qty(rights.self, 'silver'), 380);
  const duplicateRights = await h.socketAck(accounts.trade.socket, 'personalBaseAction', { action: 'resolveRights', outcomeId: 'official' });
  const stillOwned = await request(accounts.trade, 'state', { profileOnly: true });
  assert.equal(qty(stillOwned.self, 'silver'), 380, 'Rights must not be charged twice');
  const drop = await request(accounts.trade, 'dropItem', { itemId: 'artifactSpring', qty: 1 });
  assert.equal(qty(drop.self, 'artifactSpring'), 0);
  assert.deepEqual(drop.self.artifactSlots, []);
  assert.equal(drop.self.artifactEffects.speedPct, 0);
  const pickup = await request(accounts.target, 'pickupGroundItem', { id: drop.item.id });
  assert.equal(qty(pickup.self, 'artifactSpring'), 1);
  assert.equal(pickup.self.artifactRecords[0].id, 'audit_spring');
  assert.equal(pickup.self.artifactRecords[0].ownerCharacterId, accounts.target.characterId);
  assert(pickup.self.artifactRecords[0].stabilized);
  const equip = await request(accounts.target, 'artifactLoadoutAction', { action: 'equip', recordId: 'audit_spring' });
  assert.equal(equip.self.artifactEffects.speedPct, 0.08);
  const forged = await h.socketAck(accounts.trade.socket, 'artifactLoadoutAction', { action: 'equip', recordId: 'audit_spring' });
  assert(!forged.ok, 'Old owner must not equip transferred record');
  await request(accounts.trade, 'personalBaseAction', { action: 'enter' });
  const deposit = await request(accounts.trade, 'personalBaseAction', { action: 'deposit', itemId: 'artifactDrop', qty: 1 });
  assert.equal(qty(deposit.self, 'artifactDrop'), 0);
  const withdraw = await request(accounts.trade, 'personalBaseAction', { action: 'withdraw', itemId: 'artifactDrop', qty: 1 });
  const hot = withdraw.self.artifactRecords.find(row => row.id === 'audit_hot');
  assert(hot && hot.hot && !hot.stabilized, 'Storage must preserve hot artifact identity');
  const cannotEquipHot = await h.socketAck(accounts.trade.socket, 'artifactLoadoutAction', { action: 'equip', recordId: 'audit_hot' });
  assert(!cannotEquipHot.ok);
  const stable = await request(accounts.trade, 'stabilizeArtifact', { recordId: 'audit_hot' });
  assert(stable.record.stabilized && !stable.record.hot);
  await request(accounts.trade, 'artifactLoadoutAction', { action: 'equip', recordId: 'audit_hot' });
  console.log('PASS base rights and artifact drop/pickup/storage/stabilization/loadout');

  await h.connectAndJoin(accounts.cadence);
  const fire = await request(accounts.cadence, 'combatAttack', { weapon: 'laserPistol', mode: 'single', attackToken: 'regression_fire' });
  assert(fire.combat.condition < 100);
  const repair = await request(accounts.cadence, 'inventoryItemAction', {
    action: 'repair', itemId: 'laserPistol', itemRuntimeId: accounts.cadence.weaponRuntimeId, requestId: 'regression_repair'
  });
  assert.equal(repair.condition, 100);
  assert.equal(qty(repair.self, 'repairKit'), 1);
  assert.equal(repair.self.weaponInventoryRuntime.find(row => row.id === 'ui_laserPistol_spare_1').condition, 43, 'Repair must not affect another weapon of the same type');
  const badRepair = await h.socketAck(accounts.cadence.socket, 'inventoryItemAction', {
    action: 'repair', itemId: 'laserPistol', itemRuntimeId: 'ui_laserPistol_missing_123', requestId: 'regression_forged_repair'
  });
  assert(!badRepair.ok);
  const afterBad = await request(accounts.cadence, 'state', { profileOnly: true });
  assert.equal(qty(afterBad.self, 'repairKit'), 1);

  await h.connectAndJoin(accounts.persistence);
  await request(accounts.persistence, 'personalBaseAction', { action: 'enter' });
  const job = await request(accounts.persistence, 'personalBaseAction', { action: 'startJob', typeId: 'filters' });
  assert.equal(job.state.jobs.filter(row => !row.claimed).length, 1);
  assert.equal(qty(job.self, 'scrap'), 8);
  assert.equal(qty(job.self, 'chemicals'), 8);
  const jobId = job.state.jobs.find(row => !row.claimed).id;
  await h.connectAndJoin(accounts.progression);
  assert.notEqual(accounts.progression.join.locationId, 'clanSiege');
  const reenter = await h.socketAck(accounts.progression.socket, 'kromkaSiegeAction', { action: 'enter', eventId: siegeEvent.id });
  assert(!reenter.ok);
  console.log('PASS instance repair, eleventh production job and siege elimination');

  for (const account of Object.values(accounts)) h.closeSocket(account);
  await h.stopServer();
  await h.startServer();
  await h.connectAndJoin(accounts.target);
  assert(accounts.target.join.self.artifactRecords.some(row => row.id === 'audit_spring' && row.stabilized));
  assert(accounts.target.join.self.artifactSlots.includes('audit_spring'));
  await h.connectAndJoin(accounts.persistence);
  const persistedBase = await request(accounts.persistence, 'requestPersonalBaseState', {});
  assert(persistedBase.state.jobs.some(row => row.id === jobId && !row.claimed), 'Paid job must survive restart');
  await h.connectAndJoin(accounts.trade);
  const persistedRights = await request(accounts.trade, 'requestPersonalBaseState', {});
  assert(persistedRights.state.rights.granted);
  console.log('PASS server restart persistence; /health and Socket.IO exercised in isolated data');
})().catch(error => { console.error(error.stack); process.exitCode = 1; }).finally(async () => {
  for (const account of Object.values(accounts)) h.closeSocket(account);
  await h.stopServer();
  h.cleanupSync();
});
